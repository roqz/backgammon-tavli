export const DICTS = { de, en };
export type Lang = keyof typeof DICTS;

export const useT = (): Dict => DICTS[useSettings((s) => s.lang)];

/** History line with localized cube/resign records; moves keep standard notation. */
export const turnText = (t: Dict, variant: VariantId, rec: TurnRecord): string => {
  switch (rec.kind) {
    case "double":
      return `${t.histDouble} ${rec.to}`;
    case "take":
      return t.histTake;
    case "beaver":
      return `${t.histBeaver} ${rec.to}`;
    case "raccoon":
      return `${t.histRaccoon} ${rec.to}`;
    case "closed-out":
      return t.histClosedOut;
    case "drop":
      return t.histDrop;
    case "resign":
      return `${t.histResign} (${[t.single, t.gammon, t.backgammon][rec.level - 1]})`;
    default:
      return formatTurn(variant, rec);
  }
};

/** "3 Punkte", "1 Punkt" or "Geldspiel" for online lengths. */
export const lengthText = (t: Dict, length: number): string =>
  length === 0 ? t.moneySession : `${length} ${length === 1 ? t.point : t.points}`;
