/**
 * Trains a neural network evaluation by self-play with TD(0) learning (TD-Gammon style).
 *
 *   pnpm --filter @tavli/ai train-nn <model> [games=200000] [hidden=80] [workers] [resume]
 *
 * Workers play greedy 1-ply games with the shared network and update it in place without
 * locks ("Hogwild"): after every turn the evaluation of the position before the roll is moved
 * toward the evaluation after the move, at the end toward the real result. Snapshots go to
 * tuning/nn-<model>.packed; the final network is written to src/nets/<model>.ts.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { availableParallelism } from "node:os";
import { isMainThread, parentPort, Worker, workerData } from "node:worker_threads";
import {
  type Board,
  bearOffLevel,
  diceToPlay,
  type GameState,
  getVariant,
  initialBoard,
  type MoveGenerator,
  moveGenerator,
  opponent,
  type Player,
  rollDice,
  seededRng,
  type VariantId,
} from "@tavli/engine";
import {
  encode,
  encodedBuffer,
  flipOutputs,
  forward,
  NET_OUTPUTS,
  type Net,
  type NetModel,
  netInputs,
  outputEquity,
  packNet,
  randomNet,
  unpackNet,
} from "../src/nn";

const MODEL_VARIANT: Record<NetModel, VariantId> = {
  backgammon: "backgammon",
  hypergammon: "hypergammon",
  portes: "portes",
  plakoto: "plakoto",
  fevga: "fevga",
};

interface Job {
  readonly model: NetModel;
  readonly hidden: number;
  readonly games: number;
  readonly total: number;
  readonly seed: number;
  readonly buffers: {
    w1: SharedArrayBuffer;
    b1: SharedArrayBuffer;
    w2: SharedArrayBuffer;
    b2: SharedArrayBuffer;
  };
  readonly counter: SharedArrayBuffer;
  readonly alpha: [number, number];
}

const root = new URL("..", import.meta.url);

if (isMainThread) {
  const [model, gamesArg, hiddenArg, workersArg, resume] = process.argv.slice(2) as [
    NetModel,
    string?,
    string?,
    string?,
    string?,
  ];
  if (!model || !MODEL_VARIANT[model]) {
    console.error(
      "usage: train-nn <backgammon|hypergammon|portes|plakoto|fevga> [games] [hidden] [workers] [resume]",
    );
    process.exit(1);
  }
  const games = Number(gamesArg ?? 200_000);
  const workers = Number(workersArg ?? Math.max(1, availableParallelism() - 2));
  const snapshot = new URL(`tuning/nn-${model}.packed`, root);
  let start: Net;
  if (resume === "resume") {
    start = unpackNet(readFileSync(snapshot, "utf8"));
  } else {
    start = randomNet(model, Number(hiddenArg ?? 80), seededRng(42));
  }
  const share = (a: Float32Array) => {
    const sab = new SharedArrayBuffer(a.byteLength);
    new Float32Array(sab).set(a);
    return sab;
  };
  const buffers = { w1: share(start.w1), b1: share(start.b1), w2: share(start.w2), b2: share(start.b2) };
  const counter = new SharedArrayBuffer(8);
  const played = new Int32Array(counter);
  const shared = (): Net => ({
    model,
    inputs: netInputs(model),
    hidden: start.hidden,
    w1: new Float32Array(buffers.w1),
    b1: new Float32Array(buffers.b1),
    w2: new Float32Array(buffers.w2),
    b2: new Float32Array(buffers.b2),
  });
  const save = () => {
    mkdirSync(new URL("tuning/", root), { recursive: true });
    writeFileSync(snapshot, packNet(shared()));
  };
  const alpha: [number, number] = resume === "resume" ? [0.03, 0.01] : [0.1, 0.01];
  console.log(
    `training ${model}: ${games} games, ${start.hidden} hidden units, ${workers} workers, alpha ${alpha}`,
  );
  const t0 = Date.now();
  const timer = setInterval(() => {
    save();
    const n = Atomics.load(played, 0);
    const mins = (Date.now() - t0) / 60_000;
    console.log(`${n} games, ${mins.toFixed(1)} min, ${Math.round(n / mins)} games/min`);
  }, 60_000);
  let done = 0;
  for (let i = 0; i < workers; i++) {
    const job: Job = {
      model,
      hidden: start.hidden,
      games: Math.ceil(games / workers),
      total: games,
      seed: 1000 + i * 7919 + (Date.now() % 1000),
      buffers,
      counter,
      alpha,
    };
    const w = new Worker(new URL(import.meta.url), { workerData: job, execArgv: ["--import", "tsx"] });
    w.on("error", (e) => {
      console.error(e);
      process.exit(1);
    });
    w.on("exit", () => {
      if (++done < workers) return;
      clearInterval(timer);
      save();
      const packed = packNet(shared());
      mkdirSync(new URL("src/nets/", root), { recursive: true });
      writeFileSync(
        new URL(`src/nets/${model}.ts`, root),
        `// Generated by scripts/train-nn.ts (${Atomics.load(played, 0)} self-play games). Do not edit.\nexport default ${JSON.stringify(packed)};\n`,
      );
      console.log(`done in ${((Date.now() - t0) / 60_000).toFixed(1)} min`);
    });
  }
} else {
  train(workerData as Job);
  parentPort?.close();
}

function train(job: Job): void {
  const variant = MODEL_VARIANT[job.model];
  const rules = getVariant(variant);
  const net: Net = {
    model: job.model,
    inputs: netInputs(job.model),
    hidden: job.hidden,
    w1: new Float32Array(job.buffers.w1),
    b1: new Float32Array(job.buffers.b1),
    w2: new Float32Array(job.buffers.w2),
    b2: new Float32Array(job.buffers.b2),
  };
  const played = new Int32Array(job.counter);
  const rng = seededRng(job.seed);
  const gens: [MoveGenerator, MoveGenerator] = [moveGenerator(variant, 0), moveGenerator(variant, 1)];
  const H = job.hidden;
  const x = encodedBuffer();
  const xc = encodedBuffer();
  const hidden = new Float32Array(H);
  const hc = new Float32Array(H);
  const y = new Float32Array(NET_OUTPUTS);
  const yc = new Float32Array(NET_OUTPUTS);
  const target = new Float32Array(NET_OUTPUTS);
  const best = new Float32Array(NET_OUTPUTS);
  const g = new Float32Array(NET_OUTPUTS);
  const gh = new Float32Array(H);

  /** Moves the evaluation of input x (with activations hidden, outputs y) toward target. */
  const update = (alpha: number) => {
    for (let o = 0; o < NET_OUTPUTS; o++) g[o] = (target[o]! - y[o]!) * y[o]! * (1 - y[o]!);
    for (let h = 0; h < H; h++) {
      let e = 0;
      for (let o = 0; o < NET_OUTPUTS; o++) e += g[o]! * net.w2[o * H + h]!;
      gh[h] = alpha * e * hidden[h]! * (1 - hidden[h]!);
    }
    for (let o = 0; o < NET_OUTPUTS; o++) {
      const a = alpha * g[o]!;
      const row = o * H;
      for (let h = 0; h < H; h++) net.w2[row + h]! += a * hidden[h]!;
      net.b2[o]! += a;
    }
    for (let j = 0; j < x.n; j++) {
      const row = x.idx[j]! * H;
      const v = x.val[j]!;
      for (let h = 0; h < H; h++) net.w1[row + h]! += v * gh[h]!;
    }
    for (let h = 0; h < H; h++) net.b1[h]! += gh[h]!;
  };

  const endLevel = (board: Board, winner: Player, end: string): number =>
    end === "mana"
      ? 2
      : bearOffLevel(
          { variant, board, jacoby: false, cube: { enabled: false, value: 1 } } as unknown as GameState,
          winner,
        );

  for (let game = 0; game < job.games; game++) {
    const progress = Atomics.load(played, 0) / job.total;
    const alpha = job.alpha[0] + (job.alpha[1] - job.alpha[0]) * Math.min(1, progress);
    let board = initialBoard(rules);
    let turn: Player = rng() < 0.5 ? 0 : 1;
    let first = true;
    for (let ply = 0; ply < 2000; ply++) {
      // evaluation before the roll, with `turn` on roll
      forward(net, encode(job.model, variant, board, turn, x), hidden, y);
      let roll = rollDice(rng);
      while (first && roll[0] === roll[1]) roll = rollDice(rng); // opening roll: no doubles
      const dice = diceToPlay(roll[0], roll[1]);
      first = false;
      const options = gens[turn].turnOptions(board, dice);
      let bestEq = Number.NEGATIVE_INFINITY;
      let next: Board = board;
      let terminal = false;
      for (const opt of options) {
        if (opt.end) {
          const level = endLevel(opt.board, turn, opt.end);
          const eq = level;
          if (eq > bestEq) {
            bestEq = eq;
            next = opt.board;
            terminal = true;
            best[0] = 1;
            best[1] = level >= 2 ? 1 : 0;
            best[2] = level >= 3 ? 1 : 0;
            best[3] = 0;
            best[4] = 0;
          }
          continue;
        }
        forward(net, encode(job.model, variant, opt.board, opponent(turn), xc), hc, yc);
        flipOutputs(yc, target);
        const eq = outputEquity(target);
        if (eq > bestEq) {
          bestEq = eq;
          next = opt.board;
          terminal = false;
          best.set(target);
        }
      }
      if (options.length === 0 || bestEq === Number.NEGATIVE_INFINITY) {
        // no legal move: the position passes to the opponent unchanged
        forward(net, encode(job.model, variant, board, opponent(turn), xc), hc, yc);
        flipOutputs(yc, best);
      }
      target.set(best);
      update(alpha);
      if (terminal) break;
      board = next;
      turn = opponent(turn);
    }
    Atomics.add(played, 0, 1);
  }
}
